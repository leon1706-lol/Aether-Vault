// V1.6.0 native `av` launcher -- Windows AND POSIX (Linux/macOS).
//
// A small executable that speaks the daemon's real wire protocol (daemon_protocol.py,
// PROTOCOL_VERSION 1 -- a single request frame, a single response frame, no streaming, no
// cancel-over-wire) directly, without ever starting a Python interpreter, for an
// allowlisted command against a warm daemon. Falls back transparently to the real Python
// CLI for `--help`, non-allowlisted commands, no repo, no reachable daemon, or a rejected/
// forged token -- every fallback re-execs the *original, unmodified* argv, so correctness
// never depends on this binary existing at all.
//
// Scope/verification note: every Windows code path here is built AND exercised end-to-end
// on this project's own dev box against a live `av daemon`
// (tests/test_launcher_native.py, `.github/workflows/tests.yml`'s `launcher-native-windows`
// job). The POSIX branches below were written to the SAME protocol/design and reviewed with
// the same care, but this project's only dev box has no Linux/macOS toolchain to compile OR
// execute them locally -- `.github/workflows/tests.yml`'s `launcher-native-posix` job (a
// matrix over ubuntu-latest and macos-latest) is what actually builds and runs
// `tests/test_launcher_native.py` against these paths for real, since a real CI runner can
// do what this box cannot. That is a genuine difference in HOW correctness was established
// here versus the Windows side, not a lower bar for shipping it -- see
// src/launcher/README.md for the full account.
#if !defined(_WIN32) && !defined(__unix__) && !defined(__APPLE__)
#error "av_launcher.cpp supports Windows and POSIX (Linux/macOS) only"
#endif

