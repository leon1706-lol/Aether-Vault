fs::path home_dir() {
#ifdef _WIN32
    if (auto up = get_env("USERPROFILE")) return fs::u8path(*up);
    auto drive = get_env("HOMEDRIVE");
    auto path = get_env("HOMEPATH");
    if (drive && path) return fs::u8path(*drive + *path);
    if (auto home = get_env("HOME")) return fs::u8path(*home);
    return fs::current_path();
#else
    if (auto home = get_env("HOME")) return fs::u8path(*home);
    return fs::current_path();
#endif
}

fs::path user_runtime_dir() {
    if (auto xdg = get_env("XDG_RUNTIME_DIR")) return fs::u8path(*xdg) / "aether-vault";
    return home_dir() / ".aether-vault" / "run";
}

std::string sha256_hex(const std::string &s) {
    return SHA256::hash_bytes(s);
}

// Keyed by the EXACT strings this process computes for its own exe path and repo root --
// daemon_common.launcher_discovery_file() on the Python side hashes the identical two
// strings verbatim (received via AV_LAUNCHER_EXE/AV_LAUNCHER_REPO env vars during a
// fallback exec), so neither side has to agree on path-normalization rules, only on not
// re-normalizing what the other already decided.
fs::path discovery_file(const std::string &exe_s, const std::string &repo_s) {
    std::string key = sha256_hex(exe_s + "|" + repo_s).substr(0, 16);
    return user_runtime_dir() / ("launcher-" + key + ".json");
}

std::string hmac_sha256_hex(const std::string &key, const std::string &msg) {
    constexpr size_t kBlock = 64;
    std::vector<uint8_t> key_block(kBlock, 0);
    if (key.size() > kBlock) {
        SHA256 h;
        h.update(reinterpret_cast<const uint8_t *>(key.data()), key.size());
        uint8_t *d = h.digest();
        std::copy(d, d + 32, key_block.begin());
    } else {
        std::copy(key.begin(), key.end(), key_block.begin());
    }
    std::vector<uint8_t> ipad(kBlock), opad(kBlock);
    for (size_t i = 0; i < kBlock; ++i) {
        ipad[i] = key_block[i] ^ 0x36;
        opad[i] = key_block[i] ^ 0x5c;
    }
    SHA256 inner;
    inner.update(ipad.data(), ipad.size());
    inner.update(reinterpret_cast<const uint8_t *>(msg.data()), msg.size());
    uint8_t inner_digest[32];
    std::memcpy(inner_digest, inner.digest(), 32);

    SHA256 outer;
    outer.update(opad.data(), opad.size());
    outer.update(inner_digest, 32);
    return outer.hexdigest();
}

std::string random_hex(size_t nbytes) {
    std::string out;
    out.reserve(nbytes * 2);
    static const char *hexchars = "0123456789abcdef";
#ifdef _WIN32
    size_t produced = 0;
    while (produced < nbytes) {
        unsigned int r = 0;
        if (rand_s(&r) != 0) r = (unsigned int)GetTickCount64() ^ (unsigned int)produced;
        for (int b = 0; b < 4 && produced < nbytes; ++b, ++produced) {
            uint8_t byte = (uint8_t)((r >> (b * 8)) & 0xFF);
            out.push_back(hexchars[byte >> 4]);
            out.push_back(hexchars[byte & 0x0F]);
        }
    }
#else
    // /dev/urandom rather than a Linux-only getrandom()/BSD-only arc4random_buf() --
    // present and non-blocking-after-boot on every Linux and macOS this project targets.
    std::vector<uint8_t> bytes(nbytes);
    bool ok = false;
    {
        std::ifstream f("/dev/urandom", std::ios::binary);
        if (f) {
            f.read(reinterpret_cast<char *>(bytes.data()), (std::streamsize)nbytes);
            ok = f.gcount() == (std::streamsize)nbytes;
        }
    }
    if (!ok) {
        // /dev/urandom is unavailable in some minimal/sandboxed containers -- a nonce only
        // needs to be non-repeating for HMAC replay-safety within one process's requests,
        // never a secret itself, so a time+pid-seeded fallback is an acceptable last resort
        // (the token itself, the actual secret, is always read from the 0600 key file).
        uint64_t seed = (uint64_t)std::chrono::steady_clock::now().time_since_epoch().count() ^
                        (uint64_t)getpid();
        for (size_t i = 0; i < nbytes; ++i) {
            seed = seed * 6364136223846793005ULL + 1442695040888963407ULL;
            bytes[i] = (uint8_t)(seed >> 33);
        }
    }
    for (uint8_t byte : bytes) {
        out.push_back(hexchars[byte >> 4]);
        out.push_back(hexchars[byte & 0x0F]);
    }
#endif
    return out;
}

// -- transport: named pipe (Windows) / AF_UNIX socket (POSIX) -------------------------------
// Both sides implement the identical daemon_protocol.py framing (4-byte big-endian length +
// UTF-8 JSON) over whatever byte stream the platform gives us -- Conn below is the one
// pair of send_frame/recv_frame free functions every platform's connection type overloads.

#ifdef _WIN32
struct Conn {
    HANDLE h = INVALID_HANDLE_VALUE;

    Conn() = default;
    // Move-only, and NOT the compiler-generated kind: a class with a user-declared
    // destructor gets no implicit move constructor at all (C++11 rule) -- a real bug this
    // exact struct shipped once during this feature's own development (see git history /
    // Probleme.md): the by-value return from a connect helper silently fell back to the
    // implicit COPY constructor (a plain memberwise copy of the raw handle), and the
    // temporary's destructor then closed that same handle out from under the caller.
    Conn(const Conn &) = delete;
    Conn &operator=(const Conn &) = delete;
    Conn(Conn &&other) noexcept : h(other.h) { other.h = INVALID_HANDLE_VALUE; }
    Conn &operator=(Conn &&other) noexcept {
        if (this != &other) {
            if (h != INVALID_HANDLE_VALUE) CloseHandle(h);
            h = other.h;
            other.h = INVALID_HANDLE_VALUE;
        }
        return *this;
    }
    ~Conn() {
        if (h != INVALID_HANDLE_VALUE) CloseHandle(h);
    }
    bool valid() const { return h != INVALID_HANDLE_VALUE; }
};

std::optional<Conn> connect_daemon(const std::string &endpoint) {
    std::wstring wname = utf8_to_wide(endpoint);
    for (int attempt = 0; attempt < 2; ++attempt) {
        HANDLE h = CreateFileW(wname.c_str(), GENERIC_READ | GENERIC_WRITE, 0, nullptr,
                                OPEN_EXISTING, 0, nullptr);
        if (h != INVALID_HANDLE_VALUE) {
            Conn c;
            c.h = h;
            return c;
        }
        DWORD err = GetLastError();
        trace("CreateFileW attempt " + std::to_string(attempt) + " failed, GetLastError=" +
              std::to_string(err));
        if (err == ERROR_PIPE_BUSY && attempt == 0) {
            WaitNamedPipeW(wname.c_str(), 200);
            continue;
        }
        break;
    }
    return std::nullopt;
}

bool write_all(Conn &c, const uint8_t *data, size_t len) {
    size_t off = 0;
    while (off < len) {
        DWORD written = 0;
        if (!WriteFile(c.h, data + off, (DWORD)(len - off), &written, nullptr)) return false;
        if (written == 0) return false;
        off += written;
    }
    return true;
}

bool read_all(Conn &c, uint8_t *out, size_t len) {
    size_t off = 0;
    while (off < len) {
        DWORD got = 0;
        if (!ReadFile(c.h, out + off, (DWORD)(len - off), &got, nullptr)) return false;
        if (got == 0) return false;
        off += got;
    }
    return true;
}
#else
// Same move-only discipline as the Windows Conn above, for the same reason: a
// user-declared destructor suppresses the IMPLICIT move constructor too (not just the
// copy constructor), so without these explicit ones a by-value return from
// connect_daemon() below would silently fall back to a memberwise COPY of the raw fd --
// two Conn objects owning (and, on scope exit, both closing) the same socket. Written
// correctly from the start here specifically because the Windows sibling already paid for
// this exact bug once (see its own comment) -- this side has never been built or run on
// this project's Windows-only dev box, so getting it right by construction rather than by
// testing matters more here, not less.
struct Conn {
    int fd = -1;

    Conn() = default;
    Conn(const Conn &) = delete;
    Conn &operator=(const Conn &) = delete;
    Conn(Conn &&other) noexcept : fd(other.fd) { other.fd = -1; }
    Conn &operator=(Conn &&other) noexcept {
        if (this != &other) {
            if (fd >= 0) close(fd);
            fd = other.fd;
            other.fd = -1;
        }
        return *this;
    }
    ~Conn() {
        if (fd >= 0) close(fd);
    }
    bool valid() const { return fd >= 0; }
};

std::optional<Conn> connect_daemon(const std::string &endpoint) {
    int fd = socket(AF_UNIX, SOCK_STREAM, 0);
    if (fd < 0) {
        trace("socket() failed, errno=" + std::to_string(errno));
        return std::nullopt;
    }
    struct sockaddr_un addr {};
    addr.sun_family = AF_UNIX;
    if (endpoint.size() >= sizeof(addr.sun_path)) {
        trace("socket path too long for sockaddr_un: " + endpoint);
        close(fd);
        return std::nullopt;
    }
    std::memcpy(addr.sun_path, endpoint.c_str(), endpoint.size() + 1);

    // A short, bounded connect attempt (matching the Windows pipe-busy retry's own ~200ms
    // budget) via a non-blocking connect + poll, rather than trusting the OS's default
    // blocking-connect timeout (which for AF_UNIX is typically immediate success/failure
    // anyway, but a busy accept backlog on a slow/loaded box could still make this hang
    // without the timeout).
    int flags = fcntl(fd, F_GETFL, 0);
    fcntl(fd, F_SETFL, flags | O_NONBLOCK);
    int rc = connect(fd, reinterpret_cast<struct sockaddr *>(&addr), sizeof(addr));
    if (rc != 0 && errno != EINPROGRESS) {
        trace("connect() failed immediately, errno=" + std::to_string(errno));
        close(fd);
        return std::nullopt;
    }
    if (rc != 0) {
        struct pollfd pfd {};
        pfd.fd = fd;
        pfd.events = POLLOUT;
        int pr = poll(&pfd, 1, 200);
        if (pr <= 0) {
            trace("connect() timed out waiting for the daemon");
            close(fd);
            return std::nullopt;
        }
        int so_error = 0;
        socklen_t len = sizeof(so_error);
        getsockopt(fd, SOL_SOCKET, SO_ERROR, &so_error, &len);
        if (so_error != 0) {
            trace("connect() completed with error " + std::to_string(so_error));
            close(fd);
            return std::nullopt;
        }
    }
    fcntl(fd, F_SETFL, flags);  // back to blocking for the actual request/response I/O
    Conn c;
    c.fd = fd;
    return c;
}

// EINTR (a signal interrupted the blocking call before any bytes moved) is retried rather
// than treated as failure -- a real, POSIX-specific case Windows' WriteFile/ReadFile have
// no equivalent of, and one every long-lived blocking syscall on this platform is expected
// to handle. `n == 0` on write() would mean nothing was written despite no error (not
// actually possible for a stream socket short of len==0, kept as a defensive bail-out
// rather than spinning); on read() it's the real, common case -- the daemon closed its end
// of the socket, mid-frame or otherwise, and this maps that straight to the same "false =
// connection lost" contract the Windows ReadFile==0 branch already has.
bool write_all(Conn &c, const uint8_t *data, size_t len) {
    size_t off = 0;
    while (off < len) {
        ssize_t n = write(c.fd, data + off, len - off);
        if (n < 0) {
            if (errno == EINTR) continue;
            return false;
        }
        if (n == 0) return false;
        off += (size_t)n;
    }
    return true;
}

bool read_all(Conn &c, uint8_t *out, size_t len) {
    size_t off = 0;
    while (off < len) {
        ssize_t n = read(c.fd, out + off, len - off);
        if (n < 0) {
            if (errno == EINTR) continue;
            return false;
        }
        if (n == 0) return false;
        off += (size_t)n;
    }
    return true;
}
#endif

bool send_frame(Conn &c, const json &obj) {
    std::string payload = obj.dump();
    uint32_t len = (uint32_t)payload.size();
    uint8_t header[4] = {
        (uint8_t)((len >> 24) & 0xFF), (uint8_t)((len >> 16) & 0xFF),
        (uint8_t)((len >> 8) & 0xFF), (uint8_t)(len & 0xFF),
    };
    if (!write_all(c, header, 4)) return false;
    return write_all(c, reinterpret_cast<const uint8_t *>(payload.data()), payload.size());
}

std::optional<json> recv_frame(Conn &c) {
    uint8_t header[4];
    if (!read_all(c, header, 4)) return std::nullopt;
    uint32_t len = (uint32_t(header[0]) << 24) | (uint32_t(header[1]) << 16) |
                   (uint32_t(header[2]) << 8) | uint32_t(header[3]);
    constexpr uint32_t kMaxFrame = 8 * 1024 * 1024;
    if (len > kMaxFrame) return std::nullopt;
    std::string payload(len, '\0');
    if (len > 0 && !read_all(c, reinterpret_cast<uint8_t *>(payload.data()), len)) return std::nullopt;
    try {
        return json::parse(payload);
    } catch (const json::exception &) {
        return std::nullopt;
    }
}

// -- env allowlist (mirrors daemon_common.py::allowlisted_env) -----------------------------

#ifndef _WIN32
extern char **environ;
#endif

json collect_allowlisted_env() {
    json env_obj = json::object();
    static const std::vector<std::string> kExact = {"NO_COLOR", "FORCE_COLOR", "HOME",
                                                      "USERPROFILE", "COLUMNS"};
#ifdef _WIN32
    LPWCH block = GetEnvironmentStringsW();
    if (!block) return env_obj;
    for (LPWCH p = block; *p != L'\0';) {
        std::wstring entry(p);
        p += entry.size() + 1;
        size_t eq = entry.find(L'=');
        if (eq == std::wstring::npos || eq == 0) continue;  // skip "=C:=..." drive-cwd vars
        std::string key = wide_to_utf8(entry.substr(0, eq));
        std::string val = wide_to_utf8(entry.substr(eq + 1));
        bool keep = key.rfind("AV_", 0) == 0 || std::find(kExact.begin(), kExact.end(), key) != kExact.end();
        if (keep) env_obj[key] = val;
    }
    FreeEnvironmentStringsW(block);
#else
    for (char **p = environ; *p != nullptr; ++p) {
        std::string entry(*p);
        size_t eq = entry.find('=');
        if (eq == std::string::npos || eq == 0) continue;
        std::string key = entry.substr(0, eq);
        std::string val = entry.substr(eq + 1);
        bool keep = key.rfind("AV_", 0) == 0 || std::find(kExact.begin(), kExact.end(), key) != kExact.end();
        if (keep) env_obj[key] = val;
    }
#endif
    return env_obj;
}

