// -- global options mirrored from launcher.py's _GLOBAL_FLAGS / _GLOBAL_VALUE_OPTS ---------
// Keep these two lists in lockstep with python/av_cli/launcher.py -- both independently
// implement click's own global-option parsing so neither has to import click.
const std::vector<std::string> kGlobalFlags = {"--verbose", "--silent", "--version"};
const std::vector<std::string> kGlobalValueOpts = {"--output"};

// Mirrors python/av_cli/daemon_common.py::ALLOWED_COMMANDS. Deliberately duplicated rather
// than read from anywhere at runtime -- this binary is only ever trusted to match the
// Python side because AV_LAUNCHER_VERSION is baked in at the same build and the daemon
// independently rejects any cli_version it doesn't recognize (handle_request's
